/* Build the small data files that pages load instead of the full content:
     data/index.js     every doc page's sections (id, title, group) + the practice problems (id, title, difficulty, …): Revision page
     data/progress.js  window.PROGRESS: titles/groups of everything, for the dashboard and the Ctrl+K finder
     data/trace-src.js tools/trace.py as text, for stepping through your own code in the browser
   Full write-ups (code, dry runs, …) stay in the big files and load only on the pages that show them.
   Usage:  node tools/lite.js      (also run automatically at the end of tools/build.js)                       */
const fs = require("fs"), path = require("path");
const C = require("./content"), data = C.data;

const sec = (s) => ({ id: s.id, title: s.title, group: s.group });
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] != null).map((k) => [k, o[k]]));
const prac = C.prac.map((p) => pick(p, ["id", "t", "d", "cat", "p", "take", "hint"]));
fs.writeFileSync(path.join(data, "index.js"),
  "/* generated by tools/lite.js — do not edit. Light index for the Revision page (titles, groups, difficulty only). */\n" +
  C.docs.map((d) => `window.${d.list} = ${JSON.stringify(d.sections.map(sec))};\n`).join("") +
  "(" + JSON.stringify(prac) + ").forEach((p) => PRAC.push(p));\n");

const pracOrdered = PRAC_CATS.flatMap((c) => C.prac.filter((p) => p.cat === c)).map((p) => pick(p, ["id", "t", "d", "cat"]));
const progress = {
  docs: Object.fromEntries(C.docs.map((d) => [d.kind, d.sections.map(sec)])),
  prac: pracOrdered, cats: PRAC_CATS, icons: PRAC_ICONS, part: PRAC_PART,
};
fs.writeFileSync(path.join(data, "progress.js"), "/* generated by tools/lite.js — do not edit. Titles/groups of everything, for the dashboard and the Ctrl+K finder. */\nwindow.PROGRESS = " + JSON.stringify(progress) + ";\n");
// the tracer behind "Step through", so the browser can step through code you write (assets/py.js)
fs.writeFileSync(path.join(data, "trace-src.js"), "/* generated by tools/lite.js from tools/trace.py — do not edit */\nwindow.TRACE_PY = " + JSON.stringify(fs.readFileSync(path.join(__dirname, "trace.py"), "utf8")) + ";\n");
const kb = (f) => (fs.statSync(path.join(data, f)).size / 1024).toFixed(1) + " KB";
const nSec = C.docs.reduce((a, d) => a + d.sections.length, 0), total = nSec + C.prac.length;
console.log(`index files written: data/index.js (${kb("index.js")}), data/progress.js (${kb("progress.js")}): ${nSec} sections + ${C.prac.length} problems = ${total} items`);
// keep the logo ring's total (assets/site.js) in step with the content
if (SITE.ring.total !== total) {
  const sf = path.join(C.root, "assets/site.js");
  fs.writeFileSync(sf, fs.readFileSync(sf, "utf8").replace(/(ring: \{[^}]*total: )\d+/, "$1" + total));
  console.log(`  assets/site.js ring.total: ${SITE.ring.total} → ${total}`);
}

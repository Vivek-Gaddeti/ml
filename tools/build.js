/* Build step: run every code sample under tools/trace.py and generate
     data/outmap.js         which output belongs to which line (shown inline), and PLOTMAP (how many plots a sample draws)
     data/traces/<h>.js     step-by-step execution traces (loaded on demand)
     data/plots/<h>-<n>.png the matplotlib figures a sample draws
   Then refreshes the light data files (lite.js) and the version stamps on every page (stamp.js).
   Code marked to run on a computer (5th element of a code block) is skipped.
   Usage:  node tools/build.js            (takes a few minutes)                     */
const fs = require("fs"), path = require("path"), os = require("os"), { execFileSync } = require("child_process");
// Python must print UTF-8 (samples print symbols like ←, ✓), whatever the Windows console code page is; plots draw off-screen
const PYENV = { ...process.env, PYTHONIOENCODING: "utf-8", PYTHONUTF8: "1", MPLBACKEND: "Agg" };
const C = require("./content"), root = C.root;

/* ---- the SAME normalization + hash used by common.js ---- */
const norm = (c) => String(c).replace(/^\n+|\s+$/g, "");
function fnv(s) { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(16).padStart(8, "0"); }
const join = (code, run) => (run ? code.replace(/\s+$/, "") + "\n\n\n" + run : code);

/* ---- collect samples ---- */
const jobs = new Map();
function add(code, out, pre) {
  if (!code || out == null) return;
  if (norm(out) === "" && !/matplotlib/.test(code)) return;          // nothing to show (unless it draws a plot)
  const c = norm(code);
  jobs.set(fnv(c), { code: c, out: norm(out), pre: pre || "" });
}
function walk(blocks) {
  (blocks || []).forEach((b) => {
    if (!Array.isArray(b)) return;
    if (b[0] === "code" && !b[4] && !/^(bash|shell|sh|powershell|cmd|json|text)$/i.test(b[3] || "")) add(b[1], b[2]);   // Python only
    if (b[0] === "ex" && b[1].code) add(b[1].code, b[1].out);
    if (b[0] === "qa" && Array.isArray(b[2])) walk(b[2]);
  });
}
C.docs.forEach((d) => d.sections.forEach((s) => walk(s.blocks)));
C.prac.forEach((p) => {
  const pre = p.h ? C.helpers[p.h] : "";
  add(join(p.opt.code, p.run), p.out, pre);
  if (p.better && p.better.code) add(join(p.better.code, p.run), p.out, pre);
  if (p.brute && p.brute.code && p.brute.run !== false) {
    const own = typeof p.brute.run === "string";
    add(join(p.brute.code, own ? p.brute.run : p.run), own ? p.brute.out : p.out, pre);
  }
});

/* ---- run ---- */
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ai-trace-"));
const normOut = (s) => String(s).replace(/\r/g, "").split("\n").map((l) => l.replace(/\s+$/, "")).join("\n").replace(/^\n+|\n+$/g, "");
let total = 0, traced = 0, nPlots = 0;
const mismatch = [];
{
  const tdir = path.join(root, "data", "traces"), pdir = path.join(root, "data", "plots");
  [tdir, pdir].forEach((d) => { fs.rmSync(d, { recursive: true, force: true }); fs.mkdirSync(d, { recursive: true }); });
  const outmap = {}, plotmap = {};
  for (const [h, job] of jobs) {
    total++;
    const jf = path.join(tmp, "job.json"), rf = path.join(tmp, "res.json");
    fs.writeFileSync(jf, JSON.stringify(job));
    try { fs.unlinkSync(rf); } catch (e) {}
    let res = null;
    try {
      execFileSync("python", [path.join(__dirname, "trace.py"), jf, rf], { cwd: tmp, timeout: 120000, stdio: ["ignore", "ignore", "pipe"], env: PYENV });
      res = JSON.parse(fs.readFileSync(rf, "utf8"));
    } catch (e) { res = null; }
    if (!res || !res.ok || normOut(res.out) !== normOut(job.out)) { mismatch.push(h + " " + job.code.split("\n")[0].slice(0, 60) + (res && res.err ? "  → " + res.err : "")); continue; }
    // inline outputs: [[after_line, text]] with trailing newline trimmed, empty chunks dropped
    outmap[h] = res.outmap.map(([l, t]) => [l, t.replace(/\n$/, "")]).filter(([, t]) => t.trim() !== "");
    (res.imgs || []).forEach((b64, i) => fs.writeFileSync(path.join(pdir, `${h}-${i}.png`), Buffer.from(b64, "base64")));
    if (res.imgs && res.imgs.length) { plotmap[h] = res.imgs.length; nPlots += res.imgs.length; }
    fs.writeFileSync(path.join(tdir, h + ".js"),
      `(window.TRACES=window.TRACES||{})["${h}"]=` + JSON.stringify({ steps: res.steps, out: res.out, truncated: res.truncated, max: res.max }) + ";\n");
    traced++;
  }
  fs.writeFileSync(path.join(root, "data", "outmap.js"), "/* generated by tools/build.js — do not edit */\nwindow.OUTMAP=" + JSON.stringify(outmap) + ";\nwindow.PLOTMAP=" + JSON.stringify(plotmap) + ";\n");
  process.stdout.write(`${jobs.size} samples, ${nPlots} plots\n`);
}
// light index files for dashboards / progress page
execFileSync("node", [path.join(__dirname, "lite.js")], { stdio: "inherit" });
execFileSync("node", [path.join(__dirname, "stamp.js")], { stdio: "inherit" });   // fresh version stamps on every page (separate process: this one has every file loaded)
console.log(`traced ${traced}/${total}` + (mismatch.length ? `\nnot traced (${mismatch.length}):\n  ` + mismatch.join("\n  ") : ""));
